let pop = null;
export function closeEmoji() { pop?.remove(); pop = null; }

/** Opens the picker next to `anchor`; calls onPick(emoji). */
export function pickEmoji(anchor, onPick, { keepOpen = true } = {}) {
  if (pop) { closeEmoji(); return; }
  const recentKey = "du.emojiRecent";
  const recent = () => { try { return JSON.parse(localStorage.getItem(recentKey) || "[]"); } catch { return []; } };
  const cats = { "🕘 Recent": recent().join(" "), ...EMOJI };
  pop = document.createElement("div");
  pop.className = "emoji-pop glossy";
  pop.innerHTML = `<div class="emoji-tabs">${Object.keys(cats).map((c, i) => `<button data-c="${i}" title="${c.slice(2).trim()}" class="${i === (recent().length ? 0 : 1) ? "on" : ""}">${c.split(" ")[0]}</button>`).join("")}</div>
    <div class="emoji-grid"></div>`;
  document.body.appendChild(pop);
  const grid = pop.querySelector(".emoji-grid");
  const show = (i) => {
    const list = Object.values(cats)[i].split(" ").filter(Boolean);
    grid.innerHTML = list.length ? list.map((e) => `<button>${e}</button>`).join("") : `<p class="small muted" style="grid-column:1/-1">Emojis you use show up here.</p>`;
    pop.querySelectorAll("[data-c]").forEach((b) => b.classList.toggle("on", Number(b.dataset.c) === i));
  };
  pop.querySelectorAll("[data-c]").forEach((b) => (b.onclick = (e) => { e.stopPropagation(); show(Number(b.dataset.c)); }));
  grid.onclick = (e) => {
    const b = e.target.closest("button");
    if (!b) return;
    e.stopPropagation();
    const emo = b.textContent;
    const r = [emo, ...recent().filter((x) => x !== emo)].slice(0, 32);
    try { localStorage.setItem(recentKey, JSON.stringify(r)); } catch {}
    onPick(emo);
    if (!keepOpen) closeEmoji();
  };
  show(recent().length ? 0 : 1);
  const r = anchor.getBoundingClientRect();
  const w = Math.min(320, innerWidth - 12);
  pop.style.width = w + "px";
  pop.style.left = Math.max(6, Math.min(r.left, innerWidth - w - 6)) + "px";
  const h = pop.offsetHeight;
  pop.style.top = (r.top - h - 6 > 6 ? r.top - h - 6 : Math.min(r.bottom + 6, innerHeight - h - 6)) + "px";
  setTimeout(() => document.addEventListener("pointerdown", function away(ev) {
    if (pop && !pop.contains(ev.target) && ev.target !== anchor) { closeEmoji(); document.removeEventListener("pointerdown", away); }
    else if (!pop) document.removeEventListener("pointerdown", away);
  }), 0);
}
